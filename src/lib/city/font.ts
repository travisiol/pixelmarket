const UNKNOWN = ["#####", "#...#", "#...#", "#...#", "#...#", "#...#", "#####"];

export const GLYPH_W = 5;
export const GLYPH_H = 7;
/** One pixel of spacing between glyphs. */
export const ADVANCE = GLYPH_W + 1;

export function glyphOf(ch: string): string[] {
  return GLYPHS[ch.toUpperCase()] ?? UNKNOWN;
}

/** Pixel width of a string, no trailing gap. */
export function textWidth(text: string): number {
  return text.length === 0 ? 0 : text.length * ADVANCE - 1;
}

/** Every lit pixel of `text` as (x, y) in text space, y down. */
export function textPixels(text: string): [number, number][] {
  const out: [number, number][] = [];
  [...text.toUpperCase()].forEach((ch, i) => {
    const g = glyphOf(ch);
    for (let y = 0; y < GLYPH_H; y++) {
      for (let x = 0; x < GLYPH_W; x++) {
        if (g[y][x] === "#") out.push([i * ADVANCE + x, y]);
      }
    }
  });
  return out;
}

/** Draws `text` on a 2D canvas context, one pixel per glyph pixel, at (x, y) with `scale`. */
export function drawText(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, color: string, scale = 1): void {
  ctx.fillStyle = color;
  for (const [px, py] of textPixels(text)) ctx.fillRect(x + px * scale, y + py * scale, scale, scale);
}
